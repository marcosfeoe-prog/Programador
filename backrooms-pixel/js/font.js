const MARKS = {
  acute: { rows: ['...#.', '..#..'], dy: 0 },
  grave: { rows: ['.#...', '..#..'], dy: 0 },
  circ: { rows: ['..#..', '.#.#.'], dy: 0 },
  tilde: { rows: ['.##.#', '#.##.'], dy: 0 },
  uml: { rows: ['.....', '.#.#.'], dy: 0 },
  ced: { rows: ['..#..', '.##..'], dy: 9 },
};

const ACCENTED = {
  Á: ['A', 'acute'], À: ['A', 'grave'], Â: ['A', 'circ'], Ã: ['A', 'tilde'],
  É: ['E', 'acute'], Ê: ['E', 'circ'], Í: ['I', 'acute'], Ó: ['O', 'acute'],
  Ô: ['O', 'circ'], Õ: ['O', 'tilde'], Ú: ['U', 'acute'], Ü: ['U', 'uml'], Ç: ['C', 'ced'],
};

const cache = new Map();

function build(rows, mark) {
  let min = 5, max = -1;
  for (const r of rows) for (let x = 0; x < 5; x++) if (r[x] === '#') { min = Math.min(min, x); max = Math.max(max, x); }
  const pts = [];
  rows.forEach((r, y) => { for (let x = 0; x < 5; x++) if (r[x] === '#') pts.push([x - min, y + 2]); });
  if (mark) {
    const m = MARKS[mark];
    m.rows.forEach((r, y) => { for (let x = 0; x < 5; x++) if (r[x] === '#') pts.push([x - min, y + m.dy]); });
  }
  return { w: max - min + 1, pts };
}

function glyph(ch) {
  if (cache.has(ch)) return cache.get(ch);
  let g = null;
  if (RAW[ch]) g = build(RAW[ch]);
  else if (ACCENTED[ch]) g = build(RAW[ACCENTED[ch][0]], ACCENTED[ch][1]);
  cache.set(ch, g);
  return g;
}

export const LINE_H = 11;

export function textWidth(str, s = 1) {
  let w = 0;
  for (const ch of String(str).toUpperCase()) {
    const g = ch === ' ' ? null : glyph(ch);
    w += g ? (g.w + 1) * s : 4 * s;
  }
  return Math.max(0, w - s);
}

// Chama cb(x, y) para cada pixel (já escalado) do texto.
export function forEachTextPixel(str, x, y, s, cb) {
  let cx = Math.round(x);
  y = Math.round(y);
  for (const ch of String(str).toUpperCase()) {
    if (ch === ' ') { cx += 4 * s; continue; }
    const g = glyph(ch);
    if (!g) { cx += 4 * s; continue; }
    for (const [px, py] of g.pts)
      for (let a = 0; a < s; a++) for (let b = 0; b < s; b++) cb(cx + px * s + a, y + py * s + b);
    cx += (g.w + 1) * s;
  }
}

// buf: { w, h, data: Uint32Array }
export function drawText(buf, str, x, y, col, s = 1, shadow = 0, align = 'left') {
  if (align === 'center') x -= textWidth(str, s) / 2;
  else if (align === 'right') x -= textWidth(str, s);
  const { w, h, data } = buf;
  const plot = (c) => (px, py) => { if (px >= 0 && py >= 0 && px < w && py < h) data[py * w + px] = c; };
  if (shadow) forEachTextPixel(str, x + s, y + s, s, plot(shadow));
  forEachTextPixel(str, x, y, s, plot(col));
}

// Quebra um texto em linhas que caibam em maxW pixels.
export function wrapText(str, maxW, s = 1) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t, s) > maxW && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
}
