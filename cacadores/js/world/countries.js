// Custo e duração das viagens entre países (horas de jogo).
export function travelInfo(from, to) {
  if (from === to) return { cost: 0, hours: 0 };
  const south = ['brasil', 'argentina', 'chile', 'uruguai'];
  const north = ['usa', 'canada'];
  const sameBlock = (south.includes(from) && south.includes(to)) || (north.includes(from) && north.includes(to));
  return sameBlock ? { cost: 650, hours: 6 } : { cost: 1400, hours: 14 };
}

