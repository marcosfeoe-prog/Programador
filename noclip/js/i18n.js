export function t(key, vars) {
  const L = S[settings.lang] || S.en;
  let s = key.split('.').reduce((o, k) => (o ? o[k] : undefined), L);
  if (s === undefined) s = key.split('.').reduce((o, k) => (o ? o[k] : undefined), S.en) ?? key;
  if (vars && typeof s === 'string') for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
